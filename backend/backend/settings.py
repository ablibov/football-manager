def _secret_key():
    """DJANGO_SECRET_KEY from the environment, otherwise a random key generated once into the data
    directory (never committed: see .gitignore)."""
    if os.environ.get('DJANGO_SECRET_KEY'):
        return os.environ['DJANGO_SECRET_KEY']
    from django.core.management.utils import get_random_secret_key
    f = DATA_DIR / 'secret_key'
    if not f.exists():
        f.write_text(get_random_secret_key())
        f.chmod(0o600)
    return f.read_text().strip()


